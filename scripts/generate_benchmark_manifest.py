#!/usr/bin/env python3
"""
Generate benchmarks/manifest.json entries from real LEF/DEF/guide files.

Every count in the manifest is read directly out of the design files —
never hand-typed — specifically to prevent the kind of error this repo's
own manuscript draft made once already (net counts overstated up to
~125x by transcription, and an incorrect "9-16 layers" claim about the
ISPD 2018 suite, which is actually uniformly 9 layers). If a benchmark
isn't present on disk, this script cannot report on it; there is no
fallback to typed-in numbers.

Usage:
  python3 scripts/generate_benchmark_manifest.py \\
      --benchmarks ./benchmarks --output benchmarks/manifest.json
"""

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path


def sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def count_def_section(text: str, section: str) -> int:
    # DEF sections declare their count on the same line, e.g. "NETS 1234 ;"
    m = re.search(rf"\b{section}\s+(\d+)\s*;", text)
    return int(m.group(1)) if m else 0


def parse_def(def_path: Path) -> dict:
    text = def_path.read_text(errors="replace")
    design_m = re.search(r"DESIGN\s+(\S+)\s*;", text)
    die_m = re.search(
        r"DIEAREA\s*\(\s*(-?\d+)\s+(-?\d+)\s*\)\s*\(\s*(-?\d+)\s+(-?\d+)\s*\)", text
    )
    return {
        "design_name": design_m.group(1) if design_m else None,
        "net_count": count_def_section(text, "NETS"),
        "component_count": count_def_section(text, "COMPONENTS"),
        "pin_count": count_def_section(text, "PINS"),
        "special_net_count": count_def_section(text, "SPECIALNETS"),
        "die_area_um": (
            {
                "llx": int(die_m.group(1)),
                "lly": int(die_m.group(2)),
                "urx": int(die_m.group(3)),
                "ury": int(die_m.group(4)),
            }
            if die_m
            else None
        ),
    }


def parse_lef_layers(lef_path: Path) -> dict:
    text = lef_path.read_text(errors="replace")
    # A LEF LAYER block's type is declared as "TYPE ROUTING ;" (routing
    # layers) vs "TYPE CUT ;" (vias) a few lines below "LAYER <name>".
    routing_layers = []
    cut_layers = []
    for m in re.finditer(r"^LAYER\s+(\S+)\s*$", text, re.MULTILINE):
        name = m.group(1)
        # look at the next ~10 lines for this layer's TYPE
        tail = text[m.end():m.end() + 400]
        type_m = re.search(r"TYPE\s+(ROUTING|CUT|MASTERSLICE|OVERLAP)\s*;", tail)
        if not type_m:
            continue
        if type_m.group(1) == "ROUTING":
            routing_layers.append(name)
        elif type_m.group(1) == "CUT":
            cut_layers.append(name)
    return {
        "routing_layer_count": len(routing_layers),
        "routing_layers": routing_layers,
        "cut_layer_count": len(cut_layers),
    }


def build_entry(bench_dir: Path) -> dict:
    lef_files = sorted(bench_dir.glob("*.lef"))
    def_files = sorted(bench_dir.glob("*.def"))
    guide_files = sorted(bench_dir.glob("*.guide"))
    if not def_files:
        return None

    def_path = def_files[0]
    def_info = parse_def(def_path)

    layer_info = {"routing_layer_count": None, "routing_layers": [], "cut_layer_count": None}
    for lef_path in lef_files:
        info = parse_lef_layers(lef_path)
        if info["routing_layer_count"]:
            layer_info = info
            break

    checksums = {}
    for f in lef_files + def_files + guide_files:
        checksums[f.name] = {"sha256": sha256_of(f), "bytes": f.stat().st_size}

    return {
        "name": bench_dir.name,
        "source": "generated by scripts/generate_benchmark_manifest.py from files on disk",
        "def_file": def_path.name,
        "lef_files": [f.name for f in lef_files],
        "guide_files": [f.name for f in guide_files],
        "design_name": def_info["design_name"],
        "net_count": def_info["net_count"],
        "special_net_count": def_info["special_net_count"],
        "component_count": def_info["component_count"],
        "pin_count": def_info["pin_count"],
        "die_area_um": def_info["die_area_um"],
        "routing_layer_count": layer_info["routing_layer_count"],
        "routing_layers": layer_info["routing_layers"],
        "cut_layer_count": layer_info["cut_layer_count"],
        "checksums": checksums,
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--benchmarks", required=True, help="Directory containing one subdir per benchmark")
    ap.add_argument("--output", default="benchmarks/manifest.json")
    args = ap.parse_args()

    bench_root = Path(args.benchmarks)
    if not bench_root.is_dir():
        print(f"error: {bench_root} is not a directory", file=sys.stderr)
        return 1

    entries = []
    for sub in sorted(bench_root.iterdir()):
        if not sub.is_dir():
            continue
        entry = build_entry(sub)
        if entry is not None:
            entries.append(entry)
            print(f"[manifest] {entry['name']}: "
                  f"{entry['net_count']} nets, {entry['component_count']} components, "
                  f"{entry['pin_count']} pins, {entry['routing_layer_count']} routing layers "
                  f"(read from {entry['def_file']})")

    if not entries:
        print(f"warning: no benchmark subdirectories with a .def file found under {bench_root}",
              file=sys.stderr)

    manifest = {
        "schema_version": 1,
        "generated_by": "scripts/generate_benchmark_manifest.py",
        "note": (
            "All counts below are parsed directly from the LEF/DEF/guide files "
            "at generation time — never hand-typed. Re-run this script whenever "
            "benchmark files change; do not edit counts in this file by hand."
        ),
        "benchmarks": entries,
    }

    out_path = Path(args.output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with open(out_path, "w") as f:
        json.dump(manifest, f, indent=2)
    print(f"[manifest] wrote {out_path} ({len(entries)} benchmark(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
